"""Request, model-output and response shapes of Secure Prompt.

``ModelResult`` is what Gemini must produce (checked by ``validate``); ``SecurePromptOut`` is what
the API returns, with the OWASP names and a coverage table added by the server, not the model.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

__all__ = ["Bullet", "CoverageRow", "DISCLAIMER", "ModelResult", "OWASP_2021", "OwaspId", "SecurePromptOut",
           "SecurePromptRequest"]

OwaspId = Literal["A01", "A02", "A03", "A04", "A05", "A06", "A07", "A08", "A09", "A10"]

# OWASP Top 10, 2021 edition
OWASP_2021: dict[str, str] = {
    "A01": "Broken Access Control",
    "A02": "Cryptographic Failures",
    "A03": "Injection",
    "A04": "Insecure Design",
    "A05": "Security Misconfiguration",
    "A06": "Vulnerable and Outdated Components",
    "A07": "Identification and Authentication Failures",
    "A08": "Software and Data Integrity Failures",
    "A09": "Security Logging and Monitoring Failures",
    "A10": "Server-Side Request Forgery",
}

DISCLAIMER = ("Generated by an AI model and not scanned or run by AEGIS. The reasons below are the model's claims, "
              "not proof. Review the code and test it before you use it.")

MAX_PROMPT_CHARS = 2000


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class SecurePromptRequest(_Strict):
    prompt: str = Field(min_length=3, max_length=MAX_PROMPT_CHARS, description="What to build, in plain words")
    language: str = Field("python", pattern=r"^[A-Za-z0-9+#. -]{1,30}$", description="Language or framework, e.g. python, flask, node")


class Bullet(BaseModel):
    owasp: OwaspId
    action: str = Field(min_length=1, max_length=400, description="What the code does")
    why: str = Field(min_length=1, max_length=400, description="Why that makes it safer")


class ModelResult(BaseModel):
    """What the model returns for one request."""

    language: str = Field(min_length=1, max_length=40)
    code: str = Field(min_length=1, max_length=30000)
    bullets: list[Bullet] = Field(min_length=1, max_length=30)
    not_applicable: list[OwaspId] = Field(default_factory=list, max_length=10)
    not_covered: list[str] = Field(default_factory=list, max_length=12)


class BulletOut(Bullet):
    category: str


class CoverageRow(BaseModel):
    id: OwaspId
    name: str
    status: Literal["covered", "not_applicable", "not_covered"]


class SecurePromptOut(BaseModel):
    language: str
    code: str
    bullets: list[BulletOut]
    coverage: list[CoverageRow]
    not_covered: list[str]
    owasp_version: str = "2021"
    provider: str
    model: str
    verified: bool = False   # the code was not scanned or run: always False in this version
    disclaimer: str = DISCLAIMER
